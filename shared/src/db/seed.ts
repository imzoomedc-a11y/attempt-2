let seedPromise: Promise<void> | null = null;

async function runSeed() {
  // Make sure the tables exist before we read or write anything. This is what
  // lets a fresh database self-initialize on the very first request.
  await ensureSchema();

  const [jobCount] = await db
    .select({ count: sql<number>`count(*)::int` })
    .from(jobs);

  if ((jobCount?.count ?? 0) === 0) {
    await db.insert(jobs).values(seedJobs);
  }

  const [resourceCount] = await db
    .select({ count: sql<number>`count(*)::int` })
    .from(resources);

  if ((resourceCount?.count ?? 0) === 0) {
    await db.insert(resources).values(seedResources);
  }
}

/** Seeds demo content exactly once per server process. */
export function ensureSeeded() {
  if (!seedPromise) {
    seedPromise = runSeed().catch((error) => {
      seedPromise = null;
      throw error;
    });
  }
  return seedPromise;
}
